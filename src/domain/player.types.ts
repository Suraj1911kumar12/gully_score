/**
 * GullyScore Domain Contracts - Players & Teams
 */

export type PlayerRole = 'BATSMAN' | 'BOWLER' | 'ALL_ROUNDER' | 'WICKET_KEEPER';

export interface MatchPlayerEntity {
  id: string;
  matchId: string;
  teamId: string;
  name: string;
  battingOrder: number;
  isCaptain?: boolean;
  isWicketKeeper?: boolean;
  createdAt: string;
}

export interface MatchTeamEntity {
  id: string;
  matchId: string;
  name: string;
  shortName: string;
  teamSide: 'TEAM_A' | 'TEAM_B';
  createdAt: string;
}

export interface OpeningSelections {
  strikerPlayerId: string;
  nonStrikerPlayerId: string;
  openingBowlerPlayerId: string;
}

export interface PlayerDraftItem {
  id: string;
  name: string;
  isAutoGenerated: boolean;
  order: number;
}
